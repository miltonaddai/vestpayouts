import { writeFile } from "node:fs/promises";
import path from "node:path";
import { SAMPLE_NOTE, SAMPLE_ROWS, sampleTraderName } from "@vestpayouts/shared";
import { repoRoot } from "./env";

/** Regenerates supabase/seed.sql from the shared sample rows. */
export async function writeSeedSql() {
  const values = SAMPLE_ROWS.map(
    (r) =>
      `  ('sample', ${r.amount.toFixed(2)}, now() - interval '${r.hoursAgo} hours', ` +
      `now() - interval '${(r.hoursAgo + r.processingHours).toFixed(1)} hours', '${sampleTraderName(r.ref)}', '${SAMPLE_NOTE}')`,
  ).join(",\n");

  const sql = `-- ============================================================================
-- SAMPLE DATA ONLY. These rows are placeholders, NOT real Vest payouts.
-- They are tagged source = 'sample', labelled "Sample" in the UI, and hidden
-- automatically (see view public.visible_payouts) once any real payout exists.
-- Remove them any time with:  delete from public.payouts where source = 'sample';
-- Generated by \`yarn db:seed-sql\` from packages/shared/src/sample-data.ts.
-- ============================================================================

insert into public.payouts (source, amount_usd, paid_at, requested_at, trader_name, note)
values
${values};
`;

  const target = path.join(repoRoot, "supabase", "seed.sql");
  await writeFile(target, sql);
  console.log(`wrote supabase/seed.sql (${SAMPLE_ROWS.length} sample rows)`);
}
